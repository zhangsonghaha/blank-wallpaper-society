/** Fisher-Yates 洗牌算法 */
export function shuffleArray<T>(arr: T[]): T[] {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/** 从池中随机选取指定数量的壁纸（去重） */
export function pickRandomWallpapers(count = 24): string[] {
  return shuffleArray(WALLPAPER_POOL).slice(0, Math.min(count, WALLPAPER_POOL.length));
}

/** 系统设置键 */
export const SETTING_SOURCE_KEY = "login_wallpaper_source";
export const SETTING_URLS_KEY = "login_wallpaper_urls";

export type WallpaperSource = "unsplash" | "custom";

export interface LoginWallpaperConfig {
  source: WallpaperSource;
  customUrls: string[];
}

/**
 * 服务端获取登录页壁纸配置
 * 优先 system_settings，回退默认 Unsplash 池
 */
export async function getLoginWallpaperConfig(): Promise<LoginWallpaperConfig> {
  try {
    const { query } = await import("@/lib/db");
    const rows = (await query(
      "SELECT setting_key, setting_value FROM system_settings WHERE setting_key IN (?, ?)",
      [SETTING_SOURCE_KEY, SETTING_URLS_KEY]
    )) as any[];

    const map = new Map<string, string>();
    rows.forEach((r: any) => map.set(r.setting_key, r.setting_value || ""));

    const source = (map.get(SETTING_SOURCE_KEY) || "unsplash") as WallpaperSource;
    let customUrls: string[] = [];
    try {
      const raw = map.get(SETTING_URLS_KEY);
      if (raw) customUrls = JSON.parse(raw);
    } catch { /* ignore invalid JSON */ }

    return { source, customUrls };
  } catch {
    return { source: "unsplash", customUrls: [] };
  }
}
